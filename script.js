function normalizePlayerName(name) {
  return name.normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase().trim();
}

// Validate the local demo fields before running the existing stats lookup.
function validatePlayerLookupForm() {
  const playerNameInput = document.getElementById("player-lookup-name");
  const shirtNumberInput = document.getElementById("player-shirt-number");
  const fields = [playerNameInput, shirtNumberInput];
  let isValid = true;

  fields.forEach((field) => {
    field.setAttribute("aria-invalid", "false");
    document.getElementById(`${field.id}-error`).textContent = "";
  });

  if (!playerNameInput.value.trim()) {
    document.getElementById("player-lookup-name-error").textContent = "Enter a player name.";
    playerNameInput.setAttribute("aria-invalid", "true");
    isValid = false;
  } else if (playerNameInput.value.trim().length < 2) {
    document.getElementById("player-lookup-name-error").textContent = "Enter at least 2 characters.";
    playerNameInput.setAttribute("aria-invalid", "true");
    isValid = false;
  }

  const shirtNumber = Number(shirtNumberInput.value);
  if (!shirtNumberInput.value) {
    document.getElementById("player-shirt-number-error").textContent = "Enter a shirt number.";
    shirtNumberInput.setAttribute("aria-invalid", "true");
    isValid = false;
  } else if (!shirtNumberInput.validity.valid || shirtNumber < 1 || shirtNumber > 99) {
    document.getElementById("player-shirt-number-error").textContent = "Enter a whole number from 1 to 99.";
    shirtNumberInput.setAttribute("aria-invalid", "true");
    isValid = false;
  }

  return isValid;
}

if (playerLookupForm) {
  const lookupInput = document.querySelector("#player-lookup-name");
  const shirtNumberInput = document.querySelector("#player-shirt-number");
  const positionInputs = document.querySelectorAll('input[name="position"]');
  const playerOptions = document.querySelector("#player-options");
  const lookupStatus = document.querySelector("#lookup-status");
  const lookupFormStatus = document.querySelector("#lookup-form-status");
  const lookupResult = document.querySelector("#lookup-result");
  const allPlayers = [
    ...Object.values(seasonData).flatMap((season) => season.players),
    ...clubLegends
  ];
  const uniquePlayers = [...new Map(allPlayers.map((player) => [normalizePlayerName(player.name), player])).values()]
    .sort((first, second) => first.name.localeCompare(second.name));

  playerOptions.innerHTML = uniquePlayers.map((player) => `<option value="${player.name}"></option>`).join("");

  [lookupInput, shirtNumberInput].forEach((input) => {
    input.addEventListener("input", () => {
      document.getElementById(`${input.id}-error`).textContent = "";
      input.setAttribute("aria-invalid", "false");
      lookupFormStatus.textContent = "";
    });
  });
  positionInputs.forEach((input) => {
    input.addEventListener("change", () => {
      lookupFormStatus.textContent = "";
    });
  });

  playerLookupForm.addEventListener("submit", (event) => {
    event.preventDefault();
    if (!validatePlayerLookupForm()) {
      lookupFormStatus.textContent = "Please correct the highlighted fields before continuing.";
      const firstInvalidField = playerLookupForm.querySelector('[aria-invalid="true"]');
      if (firstInvalidField) firstInvalidField.focus();
      return;
    }

    const selectedPosition = playerLookupForm.querySelector('input[name="position"]:checked').value;
    lookupFormStatus.textContent = `Lookup uses the player name and position; shirt number ${shirtNumberInput.value} was not used to match players. Nothing has been sent or saved.`;
    const query = normalizePlayerName(lookupInput.value);
    const matchingName = uniquePlayers.find((candidate) => normalizePlayerName(candidate.name) === query);
    const player = matchingName && (selectedPosition === "all" || matchingName.position === selectedPosition)
      ? matchingName
      : null;

    if (!player) {
      lookupResult.hidden = true;
      lookupStatus.textContent = matchingName
        ? `${matchingName.name} is listed as a ${matchingName.position}. Choose that position or Any to see available stats.`
        : "Choose a player name from the suggestions to see available stats.";
      lookupInput.focus();
      return;
    }

    const legend = clubLegends.find((entry) => normalizePlayerName(entry.name) === query);
    const seasons = Object.entries(seasonData).flatMap(([seasonName, season]) => {
      const record = season.players.find((entry) => normalizePlayerName(entry.name) === query);
      return record ? [{ seasonName: seasonName.replace("-", "/"), seasonKey: seasonName, ...record }] : [];
    });

    lookupResult.innerHTML = `
      <div class="lookup-result-heading">
        <div><div class="section-kicker">PLAYER PROFILE</div><h2>${player.name}</h2></div>
        <span class="position-pill">${player.position}</span>
      </div>
      ${legend ? `<div class="legend-career-stats"><span>${legend.years} · REAL MADRID</span><strong>${legend.appearances}</strong><span>APPEARANCES</span><strong>${legend.goals}</strong><span>GOALS</span></div>` : ""}
      <div class="lookup-season-list">
        ${seasons.map((entry) => `
          <article class="lookup-season-row">
            <div class="lookup-season-name">${entry.seasonName}<span><a href="${fotmobSeasonUrl(entry.seasonKey)}" target="_blank" rel="noreferrer">LA LIGA · FOTMOB ↗</a></span></div>
            <div class="lookup-stat"><strong>${entry.appearances}</strong><span>APPEARANCES</span></div>
            <div class="lookup-stat"><strong>${entry.goals}</strong><span>GOALS</span></div>
            <div class="lookup-stat"><strong>${(entry.goals / entry.appearances).toFixed(2)}</strong><span>GOALS / APP</span></div>
          </article>`).join("")}
      </div>
      <p class="lookup-source">${legend ? 'Career totals cover Real Madrid first-team matches across competitions; <a href="https://www.realmadrid.com/en-US/the-club/history/football-legends" target="_blank" rel="noreferrer">view the official legends archive</a>. Season rows show La Liga data from FotMob.' : 'Showing locally stored La Liga season stats from FotMob; <a href="https://www.realmadrid.com/en-US/football/first-team/players" target="_blank" rel="noreferrer">view official Real Madrid player profiles</a>.'}</p>`;
    lookupResult.hidden = false;
    lookupStatus.textContent = `Showing ${player.name}'s available season stats.`;
  });
}

const sidebar = document.querySelector("#site-sidebar");
const sidebarToggle = document.querySelector(".sidebar-toggle");
const sidebarBackdrop = document.querySelector(".sidebar-backdrop");

if (sidebar && sidebarToggle && sidebarBackdrop) {
  function setSidebarOpen(isOpen) {
    const isMobile = window.matchMedia("(max-width: 760px)").matches;
    const shouldOpen = isMobile && isOpen;
    sidebar.classList.toggle("is-open", shouldOpen);
    sidebarToggle.setAttribute("aria-expanded", String(shouldOpen));
    sidebarToggle.setAttribute("aria-label", shouldOpen ? "Close navigation" : "Open navigation");
    sidebarToggle.querySelector("span").textContent = shouldOpen ? "×" : "☰";
    if (isMobile) {
      sidebar.setAttribute("aria-hidden", String(!shouldOpen));
      sidebar.inert = !shouldOpen;
    } else {
      sidebar.removeAttribute("aria-hidden");
      sidebar.inert = false;
    }
    sidebarBackdrop.hidden = !shouldOpen;
  }

  const mobileNavigation = window.matchMedia("(max-width: 760px)");
  setSidebarOpen(false);
  mobileNavigation.addEventListener("change", () => setSidebarOpen(false));
  sidebarToggle.addEventListener("click", () => {
    setSidebarOpen(sidebarToggle.getAttribute("aria-expanded") !== "true");
  });
  sidebarBackdrop.addEventListener("click", () => setSidebarOpen(false));
  sidebar.querySelectorAll("a").forEach((link) => {
    link.addEventListener("click", () => setSidebarOpen(false));
  });
  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape" && sidebarToggle.getAttribute("aria-expanded") === "true") {
      setSidebarOpen(false);
      sidebarToggle.focus();
    }
  });
}