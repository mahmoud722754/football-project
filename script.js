function updatePlayerInfo(card) {
  const isActive = card.matches(":hover") || card.contains(document.activeElement);
  const extraInfo = card.querySelector(".legend-extra");
  card.classList.toggle("is-highlighted", isActive);
  extraInfo.hidden = !isActive;
}

